import assert from 'node:assert/strict';
import {session} from './check-inspection-llm-selection.mjs';
const s=session('vehicle-inspection-pickup-delivery',async()=>null);
const set=rows=>s.run('state.transcript='+JSON.stringify(rows));
set([{role:'customer',text:'どれくらい時間がかかるのですか？'},{role:'staff',text:'9月30日はいかがですか？'}]);
assert.equal(s.run('inspectionUnansweredQuestions().length'),1);
assert.doesNotMatch(s.run('inspectionRepeatedQuestionReply("どれくらい時間がかかるのですか？",{}).text'),/かかる/);
s.run('state.transcript.push({role:"staff",text:"一泊2日お預かりします。"})');assert.equal(s.run('inspectionUnansweredQuestions().length'),0);
assert.equal(s.run('inspectionRepeatedQuestionReply("どれくらい時間がかかるのですか？",{}).text'),'分かりました。');
set([{role:'staff',text:'作業時間は90分です。'}]);assert.equal(s.run('inspectionRepeatedQuestionReply("今、3万キロくらいです。どれくらい時間がかかるのですか？",{audioId:"inspection_current_mileage_and_duration_customer"}).text'),'今、3万キロくらいです。');
set([{role:'customer',text:'近くのお店は、どちらのお店になりますか？'},{role:'staff',text:'お家の近くですと札内店と言う店舗があります。'}]);assert.equal(s.run('inspectionUnansweredQuestions().length'),0);
set([{role:'customer',text:'代車を用意してもらえますか？'},{role:'staff',text:'代車は用意できません。'}]);assert.equal(s.run('inspectionUnansweredQuestions().length'),0);
console.log('質問再発防止・未回答抽出・後の回答で解消・不可回答も回答扱い OK');
s.run('state.analyses=scenario.scoring.map(m=>({[m.key]:true}));state.proposedAppointment={month:"9",day:"30",hour:"10",minute:0};state.inspectionPickupOutcome="visit";state.inspectionWaitingMethod="wait";state.transcript=[]');
const base=s.run('scoreScriptedRoleplay().score');
s.run('state.transcript.push({role:"customer",text:"どれくらい時間がかかるのですか？"})');
assert.equal(s.run('scoreScriptedRoleplay().score'),base-2);
assert.match(s.run('scoreScriptedRoleplay().improve.join(" ")'),/回答不足.*作業時間/);
s.run('state.transcript.push({role:"staff",text:"作業時間は90分です。"})');assert.equal(s.run('scoreScriptedRoleplay().score'),base);
console.log('未回答2点減点・回答後の減点解消 OK');
