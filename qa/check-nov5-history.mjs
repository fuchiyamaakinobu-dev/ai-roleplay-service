import assert from 'node:assert/strict';
import {session} from './check-inspection-llm-selection.mjs';
const s=session('vehicle-inspection-pickup-delivery',async()=>null);
s.run('state.inspectionMileageVariant="120000"');
const say=async text=>{await s.say(text);return s.run('state.transcript.at(-1).text')};
assert.equal(await say('ありがとうございます。佐藤様、今回のやり市の車検、ぜひお願いしたいんですが、よろしかったですか？'),'お願いしたいんですけど、いつできますか？');
assert.equal(await say('8月1日から車検できるんですが、いつ頃ご予定させていただいたらよろしいですか？'),'土日がいいです。');
await say('今のヤリスの距離数をお伺いしてもよろしいですか？');
await say('一泊2日の車検を考えておりますが。');
assert.equal(s.run('inspectionHighMileagePlanExplained()'),true);
assert.equal(await say('土曜日ですと9月の12日が空いておりますが、いかがですか？'),'何時が空いていますか？');
assert.equal(await say('9時30分から受付できますよ。'),'では、その時間でお願いします。');
await say('車検証、自賠責保険、納税証明書をご用意ください。');
await say('佐藤様、ヤリスの車検ですね。9月12日9時30分に受け付けさせていただきます。本日はご予約ありがとうございました。お電話失礼いたします。');
assert.equal(s.run('state.ended'),true);
const r=session('vehicle-inspection-pickup-delivery',async()=>null);
r.run('state.inspectionMileageVariant="over60000"');
await r.say('一日預からせていただいて車検の方可能かなと思うのですが。9月の17日ってご都合いかがでしょうか？');
assert.equal(r.run('inspectionHighMileagePlanExplained()'),true);
await r.say('9月の17日の10時半ご来店で一日だいたい夕方16時ぐらいまで車をお預かりできればと思うのですが、いかがでしょうか。');
assert.equal(r.run('inspectionStorageScoringEvidence().completion'),true);
assert.equal(r.run('inspectionPickupReasonQuestion("何かこちらに来られないご都合などございますか？")'),true);
console.log('11月3日・4日 履歴発話 OK');
