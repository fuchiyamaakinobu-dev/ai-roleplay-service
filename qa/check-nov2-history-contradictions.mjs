import assert from 'node:assert/strict';
import {session} from './check-inspection-llm-selection.mjs';
const make=()=>{const s=session('vehicle-inspection-pickup-delivery',async()=>null);s.run('window.ROLEPLAY_INTENT_ASSIST.enabled=()=>false');return s;};
const s=make();
await s.say('車検をするにあたり確認したいことがあります。このままお電話を続けさせてもらってよろしいですか？');assert.equal(s.run('state.transcript.at(-1).text'),'大丈夫ですよ。');
await s.say('オイル交換と車検で90分でできます。どこか用事があったりとかすることありますか？');assert.match(s.run('state.transcript.at(-1).text'),/代車/);
s.run('state.inspectionPickupActive=true;state.inspectionPickupPhase="proposal";state.inspectionPickupReason="work"');
await s.say('土曜日でしたら代車もご用意できますので、ご来店頂ければ助かります。');assert.equal(s.run('state.inspectionPickupOutcome'),'visit');assert.equal(s.run('state.inspectionPickupActive'),false);
await s.say('9月19日9時30分はいかがですか？');assert.doesNotMatch(s.run('state.transcript.at(-1).text'),/取りに/);
assert.equal(s.run('inspectionPickupReasonQuestion("こちらに来られない状況等ございますか？")'),true);
assert.equal(s.run('inspectionVisitStoreName("佐藤様のお家の近くですと札内店と言う店舗が近くにあるんですけれどもいかがでしょうか")'),'札内店');
for(const t of ['他のお店でやってくださいさよなら','他のお店で受けてくださいさようなら'])assert.equal(s.run('isInspectionServiceDismissal('+JSON.stringify(t)+')'),true);
s.run('state.proposedAppointment={month:"9",day:"10",hour:"9",minute:30}');
assert.equal(s.run('inspectionAppointmentContradicts("9月10日お待ちしております")'),false);assert.equal(s.run('inspectionAppointmentContradicts("9月11日お待ちしております")'),true);
s.run('state.transcript=[{role:"staff",text:"9月30日朝10時にご来店頂いて。16時半にお引き渡しさせていただければと思います。"}]');assert.equal(s.run('inspectionStorageScoringEvidence().completion'),true);
console.log('11月2日: 来店了承保持・最後の質問・状況確認・店舗保持・辞退・省略と矛盾の区別・終了日時 OK');
const benefit=make();benefit.run('state.inspectionPickupActive=true;state.inspectionPickupPhase="proposal";state.inspectionPickupReason="competitor"');
for(let i=0;i<3;i++)await benefit.say('お店の方で工場の方から直接佐藤様に整備の内容などをお伝えしたかったのですがいかがですか？');
assert.equal(benefit.run('state.inspectionPickupOutcome'),'visit');
assert.equal(benefit.run('state.transcript.at(-1).text'),'それなら、お店に持って行きます。');
await benefit.say('9月30日10時半にご来店でお願いします。');assert.doesNotMatch(benefit.run('state.transcript.at(-1).text'),/引き取り/);
