s.say('9月17日9時30分はいかがでしょうか？');
assert.equal(s.say('9月17日お伺いするんですが、何点かお願い事がございますが、よろしいですか？'),'大丈夫ですよ。');
assert.equal(s.run('state.inspectionAppointmentCandidate.minute'),30);
